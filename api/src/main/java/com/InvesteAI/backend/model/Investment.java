package com.InvesteAI.backend.model;

import com.github.f4b6a3.uuid.UuidCreator;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.UUID;

/**
 * Entity representing an individual investment holding position or trade lot.
 * <p>
 * Stores ticker symbol, company name, purchase date, unit price, quantity held,
 * current market price, and computed profit metrics.
 * </p>
 */
@Entity
@Table(name = "investment")
@Getter
@Setter
@NoArgsConstructor
public class Investment {

    /**
     * Unique identifier for the investment holding.
     */
    @Id
    @Column(name = "investment_id", nullable = false, updatable = false)
    private UUID investmentId;

    /**
     * The UUID of the user who owns this investment holding.
     */
    @Column(name = "user_id", nullable = false)
    private UUID userId;

    /**
     * Asset or company name (e.g. Petrobras PN, Vale ON).
     */
    @Column(nullable = false, length = 380)
    private String name;

    /**
     * Asset ticker symbol (e.g. PETR4, VALE3, HGLG11).
     */
    @Column(nullable = false, length = 25)
    private String symbol;

    /**
     * Date when the holding lot was acquired.
     */
    @Column(name = "purchase_date", nullable = false)
    private LocalDate purchaseDate;

    /**
     * Acquisition price per unit.
     */
    @Column(name = "purchase_unit_price", nullable = false, precision = 24, scale = 10)
    private BigDecimal purchaseUnitPrice;

    /**
     * Original quantity purchased.
     */
    @Column(name = "original_quantity", nullable = false, precision = 24, scale = 10)
    private BigDecimal originalQuantity;

    /**
     * Current remaining active quantity in portfolio.
     */
    @Column(name = "remaining_quantity", nullable = false, precision = 24, scale = 10)
    private BigDecimal remainingQuantity;

    /**
     * Current live or marked-to-market unit price.
     */
    @Column(name = "current_price", precision = 24, scale = 10)
    private BigDecimal currentPrice;

    @Enumerated(EnumType.STRING)
    @Column(name = "investment_type", nullable = false, length = 20)
    private InvestmentType investmentType = InvestmentType.VARIABLE_INCOME;

    @Column(name = "annual_rate", precision = 9, scale = 4)
    private BigDecimal annualRate;

    @Column(length = 16)
    private String fixedProduct;

    @Column(length = 100)
    private String institution;

    @Column(precision = 9, scale = 4)
    private BigDecimal cdiPercentage;

    private LocalDate maturityDate;

    /**
     * Computed profit generated by database generated column if enabled.
     */
    @Column(name = "profit", insertable = false, updatable = false, precision = 49, scale = 20)
    private BigDecimal profit;

    /**
     * Pre-persists default UUID, acquisition date, and fallback price/quantities before insert.
     */
    @PrePersist
    public void prePersist() {
        if (investmentId == null) {
            investmentId = UuidCreator.getTimeOrderedEpoch();
        }
        if (purchaseDate == null) {
            purchaseDate = LocalDate.now();
        }
        if (remainingQuantity == null) {
            remainingQuantity = originalQuantity;
        }
    }
}
